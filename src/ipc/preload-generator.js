export function renderPreload(kind, channels = channelNames) {
  const common = commonSource(channels)
  if (kind === 'management') {
    return `${common}const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args)
const subscribe = callback => {
  if (typeof callback !== 'function') return () => {}
  const listener = (_event, status) => callback(status)
  ipcRenderer.on(channels.status.changed, listener)
  return () => ipcRenderer.removeListener(channels.status.changed, listener)
}

contextBridge.exposeInMainWorld('dshDesktop', Object.freeze({
  status: Object.freeze({ get: () => invoke(channels.status.get), subscribe }),
  mode: Object.freeze({ get: () => invoke(channels.mode.get), set: mode => invoke(channels.mode.set, mode) }),
  candidate: Object.freeze({
    status: () => invoke(channels.candidate.status),
    prepare: channel => invoke(channels.candidate.prepare, channel),
    activate: candidateId => invoke(channels.candidate.activate, candidateId),
  }),
  update: Object.freeze({
    probe: () => invoke(channels.update.probe),
    check: () => invoke(channels.update.check),
    restore: () => invoke(channels.update.restore),
    desktopCheck: () => invoke(channels.update.desktopCheck),
  }),
  snapshots: Object.freeze({
    list: () => invoke(channels.snapshots.list),
    create: () => invoke(channels.snapshots.create),
    restore: snapshotId => invoke(channels.snapshots.restore, snapshotId),
  }),
  recovery: Object.freeze({
    startPluginSafeMode: () => invoke(channels.plugins.safeStart),
    exitPluginSafeMode: () => invoke(channels.plugins.safeExit),
  }),
  logs: Object.freeze({ read: (limit = 200) => invoke(channels.logs.read, limit), open: () => invoke(channels.logs.open) }),
  workspace: Object.freeze({ open: () => invoke(channels.workspace.open) }),
  app: Object.freeze({ restart: () => invoke(channels.app.restart), navigate: route => invoke(channels.app.navigate, route) }),
}))
`
  }
  if (kind === 'workspace') {
    return `${common}${workspaceTitlebarSource()}contextBridge.exposeInMainWorld('dshDesktop', Object.freeze({
  openPath: (path, intent = 'auto') => ipcRenderer.invoke(channels.openPath, path, intent),
  openSettingsDocument: () => ipcRenderer.invoke(channels.workspace.openSettings),
  openUpdate: () => ipcRenderer.invoke(channels.workspace.openUpdate),
  checkUpdate: () => ipcRenderer.invoke(channels.workspace.updateCheck),
  getUpdates: () => ipcRenderer.invoke(channels.updates.get),
  openUpdateLink: kind => ipcRenderer.invoke(channels.updates.open, kind),
  checkUpdates: () => ipcRenderer.invoke(channels.updates.check),
  executeUpdates: request => ipcRenderer.invoke(channels.updates.execute, request),
  onUpdatesChanged: callback => {
    if (typeof callback !== 'function') return () => {}
    const listener = (_event, value) => callback(value)
    ipcRenderer.on(channels.updates.changed, listener)
    return () => ipcRenderer.removeListener(channels.updates.changed, listener)
  },
  installMarketPlugin: request => ipcRenderer.invoke(channels.plugins.marketInstall, request),
  updateMarketPlugin: request => ipcRenderer.invoke(channels.plugins.marketUpdate, request),
  activateMarketUpdate: () => ipcRenderer.invoke(channels.plugins.activateMarketUpdate),
  startSafeMode: () => ipcRenderer.invoke(channels.plugins.safeStart),
  restart: () => ipcRenderer.invoke(channels.app.restart),
  openLogs: () => ipcRenderer.invoke(channels.logs.open),
  publishWorkspaceContext: context => ipcRenderer.send(channels.workspaceContext, context),
  reportTheme: theme => ipcRenderer.send(channels.workspace.theme, theme),
}))
`
  }
  if (kind === 'splash') {
    return `${common}const invoke = (channel, ...args) => ipcRenderer.invoke(channel, ...args)
const onboarding = deepFreeze(${onboardingChannelsSource()})
const subscribeProgress = callback => {
  if (typeof callback !== 'function') return () => {}
  const listener = (_event, progress) => callback(progress)
  ipcRenderer.on(onboarding.progress, listener)
  return () => ipcRenderer.removeListener(onboarding.progress, listener)
}

contextBridge.exposeInMainWorld('dshOnboarding', Object.freeze({
  recommendations: () => invoke(onboarding.recommendations),
  install: request => invoke(onboarding.install, request),
  progress: Object.freeze({ subscribe: subscribeProgress }),
  skip: () => invoke(onboarding.skip),
  window: Object.freeze({
    minimize: () => invoke(onboarding.window.minimize),
    toggleMaximize: () => invoke(onboarding.window.toggleMaximize),
    close: () => invoke(onboarding.window.close),
  }),
}))
`
  }
  throw new TypeError(`Unknown preload kind: ${String(kind)}`)
}

export function generatePreloads(root = PROJECT_ROOT) {
  const directory = generatedDirectory(root)
  mkdirSync(directory, { recursive: true })
  const generated = []
  for (const [kind, filename] of Object.entries(PRELOAD_FILES)) {
    const source = renderPreload(kind)
    const generatedPath = join(directory, filename)
    writeFileSync(generatedPath, source, 'utf8')
    generated.push(generatedPath)
  }
  return Object.freeze(generated)
}
