import { mkdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import channelNames from './channels.cjs'
import { ONBOARDING_CHANNELS } from '../onboarding.js'

const PROJECT_ROOT = fileURLToPath(new URL('../../', import.meta.url))

export const PRELOAD_FILES = Object.freeze({
  management: 'preload.cjs',
  workspace: 'workspace-preload.cjs',
  splash: 'splash-preload.cjs',
})

function generatedDirectory(root) {
  return join(root, 'build', 'preload')
}

export function generatedPreloadPath(kind, root = PROJECT_ROOT) {
  const filename = PRELOAD_FILES[kind]
  if (filename === undefined) throw new TypeError(`Unknown preload kind: ${String(kind)}`)
  return join(generatedDirectory(root), filename)
}

function channelsSource(channels) {
  if (channels === undefined || channels === null || typeof channels !== 'object' || Array.isArray(channels)) {
    throw new TypeError('Invalid IPC channel definition')
  }
  const serialized = JSON.stringify(channels, null, 2)
  if (typeof serialized !== 'string') throw new TypeError('IPC channel definition is not serializable')
  return serialized
}

function onboardingChannelsSource() {
  return JSON.stringify(ONBOARDING_CHANNELS, null, 2)
}

function commonSource(channels) {
  return `// Generated by scripts/generate-preloads.mjs from src/ipc/channels.cjs.\n// Do not edit this file; change the canonical channel definition instead.\n'use strict'\n\nconst { contextBridge, ipcRenderer } = require('electron')\n\nfunction deepFreeze(value) {\n  if (value === null || typeof value !== 'object' || Object.isFrozen(value)) return value\n  for (const child of Object.values(value)) deepFreeze(child)\n  return Object.freeze(value)\n}\n\nconst channels = deepFreeze(${channelsSource(channels)})\n\n`
}

